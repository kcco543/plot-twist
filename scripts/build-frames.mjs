function frame([h, f, s, o = INK]) {
  const N = 12;
  const g = Array.from({ length: N }, (_, y) =>
    Array.from({ length: N }, (_, x) => {
      if (y === 0 || x === 0 || y === N - 1 || x === N - 1) return o;
      if (y === N - 2 || x === N - 2) return s;
      if (y === 1 || x === 1) return h;
      return f;
    }),
  );
  for (const [cx, cy, dx, dy] of [[0, 0, 1, 1], [N - 1, 0, -1, 1], [0, N - 1, 1, -1], [N - 1, N - 1, -1, -1]]) {
    g[cy][cx] = null; g[cy][cx + dx] = null; g[cy + dy][cx] = null; g[cy + dy][cx + dx] = o;
  }
  let rects = "";
  g.forEach((row, y) => row.forEach((c, x) => { if (c) rects += `<rect x='${x}' y='${y}' width='1' height='1' fill='${c}'/>`; }));
  const svg = `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 12 12' width='12' height='12' shape-rendering='crispEdges'>${rects}</svg>`;
  return `url("data:image/svg+xml,${svg.replace(/#/g, "%23").replace(/</g, "%3C").replace(/>/g, "%3E")}")`;
}

let css = "/* GENERATED by scripts/build-frames.mjs. Do not edit by hand. */\n:root {\n";
for (const [name, cols] of Object.entries(FRAMES)) css += `  --frame-${name}: ${frame(cols)};\n`;
css += "}\n";
fs.writeFileSync(new URL("../src/app/frames.css", import.meta.url), css);
console.log(`Wrote ${Object.keys(FRAMES).length} frames.`);
